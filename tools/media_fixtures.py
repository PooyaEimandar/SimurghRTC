#!/usr/bin/env python3
"""Materialize versioned byte-exact media inputs; verify manifest and generated UE adapter."""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
import struct

ROOT = Path(__file__).resolve().parents[1]
FIXTURES = ROOT / 'Fixtures/media/v1'
HEADER = ROOT / 'Plugins/SimurghRTC/Source/SimurghRTCNative/Private/Fixtures/SimurghRTCMediaFixtureV1.h'
FIXTURE_ID = 'simurghrtc-media-v1'


def artifacts():
    tone = json.loads((FIXTURES / 'tone-period.json').read_text())
    samples = tone['samples']
    metadata = {key: value for key, value in tone.items() if key != 'samples'}
    if (metadata != {'sample_rate': 48000, 'frequency_hz': 440, 'amplitude': 8000, 'period_frames': 1200}
            or len(samples) != 1200 or any(type(v) is not int or abs(v) > 8000 for v in samples)):
        raise ValueError('Invalid canonical tone period')
    pcm = b''.join(struct.pack('<hh', samples[n % 1200], samples[n % 1200]) for n in range(48000))
    wave = struct.pack('<4sI4s4sIHHIIHH4sI', b'RIFF', 36 + len(pcm), b'WAVE', b'fmt ', 16, 1, 2,
                       48000, 192000, 4, 16, b'data', len(pcm)) + pcm
    video = bytearray()
    for frame in range(12):
        high = 160 + 4 * frame
        for y in range(64):
            for x in range(64):
                red, green, blue = ((high, 30, 30) if x < 32 else (30, high, 30)) if y < 32 else ((30, 30, high) if x < 32 else (high, high, 30))
                video += bytes([blue, green, red, 255])
    return {'tone.s16le': pcm, 'tone.wav': wave, 'quadrants.bgra': bytes(video)}


def header_text():
    samples = json.loads((FIXTURES / 'tone-period.json').read_text())['samples']
    rows = '\n'.join('    ' + ', '.join(str(v) for v in samples[i:i + 20]) + ',' for i in range(0, len(samples), 20))
    return '''// Copyright SimurghRTC contributors. SPDX-License-Identifier: Apache-2.0
// Generated by tools/media_fixtures.py from Fixtures/media/v1. Do not edit by hand.
#pragma once
#include "CoreMinimal.h"
namespace SimurghRTC::FixtureV1
{
inline constexpr int32 Width = 64, Height = 64, FrameCount = 12, SampleRate = 48000;
inline constexpr int16 TonePeriod[1200] = {
''' + rows + '''
};
inline int16 AudioSample(int32 Frame) { return TonePeriod[Frame % 1200]; }
inline FColor VideoPixel(int32 X, int32 Y, int32 Frame)
{
    const uint8 High = 160 + Frame * 4;
    if (Y < Height / 2) return X < Width / 2 ? FColor(High, 30, 30) : FColor(30, High, 30);
    return X < Width / 2 ? FColor(30, 30, High) : FColor(High, High, 30);
}
}
'''


def manifest():
    return {'schema': 1, 'fixture_id': FIXTURE_ID,
            'video': {'format': 'BGRA8', 'width': 64, 'height': 64, 'frames': 12, 'fps': 30,
                      'first_rtp_timestamp': 90000, 'rtp_timestamp_step': 3000},
            'audio': {'format': 'PCM_S16LE', 'sample_rate': 48000, 'channels': 2, 'frames': 48000,
                      'frequency_hz': 440, 'amplitude': 8000, 'period_frames': 1200},
            'files': {name: {'bytes': len(data), 'sha256': hashlib.sha256(data).hexdigest()} for name, data in artifacts().items()},
            'ue_header_sha256': hashlib.sha256(header_text().encode()).hexdigest()}


def check():
    if json.loads((FIXTURES / 'manifest.json').read_text()) != manifest() or HEADER.read_text() != header_text():
        raise ValueError('Media fixture drift: review version and regenerate manifest/header deliberately.')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--check', action='store_true')
    mode.add_argument('--refresh', action='store_true', help='Maintainer operation after reviewing a fixture-version change.')
    mode.add_argument('--output', type=Path)
    args = parser.parse_args()
    if args.refresh:
        HEADER.parent.mkdir(parents=True, exist_ok=True)
        HEADER.write_text(header_text())
        (FIXTURES / 'manifest.json').write_text(json.dumps(manifest(), indent=2) + '\n')
    else:
        check()
        if args.output:
            if args.output.exists() and any(args.output.iterdir()):
                parser.error('Output must be new or empty.')
            args.output.mkdir(parents=True, exist_ok=True)
            for name, data in artifacts().items():
                (args.output / name).write_bytes(data)
            (args.output / 'manifest.json').write_text(json.dumps(manifest(), indent=2) + '\n')
    print(FIXTURE_ID + ': verified')


if __name__ == '__main__':
    main()
